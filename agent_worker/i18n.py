# Accept-Language tags that name a Chinese script by region.
_HANT_REGIONS = {"tw", "hk", "mo"}
_BY_LOWER = {code.lower(): code for code in LANGUAGES}
_TAG = re.compile(r"^[A-Za-z]{1,8}(?:-[A-Za-z0-9]{1,8})*$|^\*$")


def _match(tag: str) -> str | None:
    tag = tag.strip().replace("_", "-").lower()
    if not tag or tag == "*":
        return None
    if tag in _BY_LOWER:
        return _BY_LOWER[tag]
    parts = tag.split("-")
    if parts[0] == "zh":
        rest = set(parts[1:])
        return "zh-Hant" if "hant" in rest or (rest & _HANT_REGIONS and "hans" not in rest) else "zh-Hans"
    return _BY_LOWER.get(parts[0])


def negotiate(header: str | None) -> str:
    """The best supported language for an Accept-Language header ("de-DE,de;q=0.9,en;q=0.8"); English
    when there is none, nothing fits or the header is garbage."""
    if not header or not isinstance(header, str):
        return DEFAULT
    ranked: list[tuple[float, int, str]] = []
    for index, item in enumerate(header[:1000].split(",")):
        tag, _, params = item.strip().partition(";")
        tag = tag.strip().replace("_", "-")
        if not tag or not _TAG.match(tag):
            continue
        q = 1.0
        for param in params.split(";"):
            name, _, value = param.strip().partition("=")
            if name.strip().lower() == "q":
                try:
                    q = float(value)
                except ValueError:
                    q = 0.0
        if q > 0:
            ranked.append((-q, index, tag))
    for _, _, tag in sorted(ranked):
        found = _match(tag)
        if found:
            return found
        if tag == "*":
            return DEFAULT
    return DEFAULT


def from_headers(headers: Mapping[str, str] | None) -> str:
    """negotiate() on a request's headers (any mapping; HTTP header names are case-insensitive)."""
    if not headers:
        return DEFAULT
    try:
        value = headers.get("accept-language") or headers.get("Accept-Language")
    except Exception:
        return DEFAULT
    return negotiate(value)


def msg(key: str, **params: Any) -> Msg:
    """A message to render later, in whatever language its reader asks for."""
    if key not in MESSAGES[DEFAULT]:
        raise KeyError(key)
    return {"key": key, "params": params}


def is_msg(value: Any) -> bool:
    return isinstance(value, dict) and isinstance(value.get("key"), str) and value["key"] in MESSAGES[DEFAULT]


def _param(lang: str, value: Any) -> Any:
    if is_msg(value):
        return render(lang, value)
    if isinstance(value, (list, tuple)):
        return "; ".join(str(_param(lang, item)) for item in value)
    return value


def t(lang: str, key: str, **params: Any) -> str:
    """The text for key in lang (English when lang or the key is missing there)."""
    table = MESSAGES.get(lang) or MESSAGES[DEFAULT]
    template = table.get(key) or MESSAGES[DEFAULT][key]
    values = {name: _param(lang, value) for name, value in params.items()}
    try:
        return template.format(**values)
    except (KeyError, IndexError, ValueError):
        return MESSAGES[DEFAULT][key].format(**values)


def render(lang: str, message: Msg | str | None) -> str:
    """A msg() in lang; a plain string as it is."""
    if message is None:
        return ""
    if isinstance(message, str):
        return message
    return t(lang, message["key"], **(message.get("params") or {}))


def english(message: Msg | str | None) -> str:
    return render(DEFAULT, message)


def split(reason: Msg | str | None) -> tuple[str, Msg | None]:
    """(English text, the message or None) for a reason that may be either a msg() or plain text."""
    if is_msg(reason):
        return english(reason), reason  # type: ignore[arg-type]
    return str(reason or ""), None


_CALLING = re.compile(r"^Calling (.+)\.\.\.$", re.S)


def event_text(event: Mapping[str, Any], lang: str) -> str:
    """A job event's line for people: its msg() in lang if it has one, else its text."""
    text = str(event.get("text") or event.get("message") or "")
    message = event.get("i18n")
    if is_msg(message):
        return render(lang, message)
    if lang != DEFAULT and event.get("type") == "tool" and event.get("phase") == "start":
        found = _CALLING.match(text)
        if found:
            return t(lang, "step.calling", tool=found.group(1))
    return text


def placeholders(template: str) -> set[str]:
    return {name for _, name, _, _ in string.Formatter().parse(template) if name}
